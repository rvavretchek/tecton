import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parse } from 'yaml';
import { afterEach, describe, expect, it } from 'vitest';
import { run } from './cli.js';
import { databasesSql, envExample } from './dev-services.js';

const created: string[] = [];
afterEach(() => {
  for (const dir of created.splice(0)) rmSync(dir, { recursive: true, force: true });
});

async function cli(args: string[], cwd: string) {
  let stdout = '';
  let stderr = '';
  const code = await run(args, {
    cwd,
    stdout: { write: (text: string) => void (stdout += text) },
    stderr: { write: (text: string) => void (stderr += text) },
  });
  return { code, stdout, stderr };
}

async function workspace(db?: string): Promise<string> {
  const parent = mkdtempSync(join(tmpdir(), 'tecton-dev-'));
  created.push(parent);
  const result = await cli(['new', 'acme', ...(db ? ['--db', db] : [])], parent);
  expect(result.code, result.stderr).toBe(0);
  return join(parent, 'acme');
}

const read = (root: string, file: string) => readFileSync(join(root, file), 'utf8');
type Compose = { name: string; services: Record<string, Record<string, any>>; volumes: Record<string, unknown> };

describe('Dev Services generated by tecton-admin new (AC 1, AC 4)', () => {
  it.each([
    ['postgres', 'postgres:18-alpine', '127.0.0.1:5432:5432'],
    ['mariadb', 'mariadb:11.8', '127.0.0.1:3306:3306'],
    ['mysql', 'mysql:8.4', '127.0.0.1:3306:3306'],
  ])('Given --db %s, When the workspace is created, Then the compose file has Valkey 9.1 and that database', async (db, image, port) => {
    const root = await workspace(db);
    const compose = parse(read(root, 'docker-compose.dev.yml')) as Compose;

    expect(compose.name).toBe('acme-dev');
    expect(compose.services['valkey']).toMatchObject({ image: 'valkey/valkey:9.1-alpine', ports: ['127.0.0.1:6379:6379'] });
    expect(compose.services['database']).toMatchObject({ image, ports: [port] });
    expect(compose.services['database']?.['healthcheck']).toBeDefined();
    expect(compose.services['database-init']).toMatchObject({
      image,
      depends_on: { database: { condition: 'service_healthy' } },
      restart: 'no',
    });
    expect(JSON.parse(read(root, 'package.json'))['tecton']).toEqual({ devServices: { database: db } });
  });

  it('Given no --db, When the workspace is created, Then PostgreSQL is the default', async () => {
    const root = await workspace();

    expect((parse(read(root, 'docker-compose.dev.yml')) as Compose).services['database']?.['image']).toBe('postgres:18-alpine');
  });

  it('Given an unsupported --db, When run, Then it fails listing the options and writes nothing', async () => {
    const parent = mkdtempSync(join(tmpdir(), 'tecton-dev-'));
    created.push(parent);
    const result = await cli(['new', 'acme', '--db', 'oracle'], parent);

    expect(result.code).toBe(1);
    expect(result.stderr).toContain('use one of: postgres, mariadb, mysql');
  });

  it('starts with an English warning that it is for development only', async () => {
    const text = read(await workspace(), 'docker-compose.dev.yml');

    expect(text.split('\n')[0]).toBe('# Tecton Dev Services: FOR LOCAL DEVELOPMENT ONLY, NEVER FOR PRODUCTION.');
    expect(text).toMatch(/^[\x09\x0A\x0D\x20-\x7E]+$/);
  });

  it('points .env.example to Valkey before any domain exists', async () => {
    expect(read(await workspace(), '.env.example')).toContain('TECTON_VALKEY_URL=redis://localhost:6379');
  });
});

describe('one logical database per domain (AC 1, AC 2)', () => {
  it('Given generated domains, When Dev Services are regenerated, Then each domain has its database and env URL', async () => {
    const root = await workspace();
    await cli(['generate', 'domain', 'finance', 'leave-requests'], root);

    const sql = read(root, 'dev-services/databases.sql');
    expect(sql).toContain("SELECT 'CREATE DATABASE \"finance\"' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'finance')\\gexec");
    expect(sql).toContain('leave_requests');
    const env = read(root, '.env.example');
    expect(env).toContain('TECTON_FINANCE_DATABASE_URL=postgresql://tecton:tecton@localhost:5432/finance');
    expect(env).toContain('TECTON_LEAVE_REQUESTS_DATABASE_URL=postgresql://tecton:tecton@localhost:5432/leave_requests');
  });

  it('Given a domain generated later, When generate runs again, Then its database is added too', async () => {
    const root = await workspace('mariadb');
    await cli(['generate', 'domain', 'finance'], root);
    await cli(['generate', 'domain', 'billing'], root);
    const sql = read(root, 'dev-services/databases.sql');

    expect(sql).toContain('CREATE DATABASE IF NOT EXISTS `finance`;');
    expect(sql).toContain('CREATE DATABASE IF NOT EXISTS `billing`;');
    expect(sql).toContain("GRANT ALL PRIVILEGES ON `billing`.* TO 'tecton'@'%';");
    expect(read(root, '.env.example')).toContain('TECTON_BILLING_DATABASE_URL=mysql://tecton:tecton@localhost:3306/billing');
  });
});

describe('generators', () => {
  it('produce a harmless SQL file when there is no domain yet', () => {
    expect(databasesSql('postgres', [])).toContain('SELECT 1;');
  });

  it('use the mysql URL scheme for MariaDB (Prisma mysql provider)', () => {
    expect(envExample('mariadb', ['finance'])).toContain('mysql://tecton:tecton@localhost:3306/finance');
  });
});
